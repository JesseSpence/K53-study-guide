-- K53 Study App schema
create extension if not exists pgcrypto;

create type public.difficulty_level as enum ('easy','medium','hard');
create type public.question_kind as enum ('multiple_choice','true_false','sign_identification','scenario');
create type public.progress_state as enum ('not_started','in_progress','completed');

create table public.modules (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  title text not null,
  description text,
  icon text,
  accent text,
  position int not null default 0,
  pass_score int,
  question_count int,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.lessons (
  id uuid primary key default gen_random_uuid(),
  module_id uuid not null references public.modules(id) on delete cascade,
  slug text not null,
  title text not null,
  summary text,
  body_md text,
  position int not null default 0,
  estimated_minutes int not null default 5,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(module_id, slug)
);

create table public.facts (
  id uuid primary key default gen_random_uuid(),
  lesson_id uuid not null references public.lessons(id) on delete cascade,
  fact_type text not null check (fact_type in ('rule','number','tip','trap','definition')),
  title text not null,
  content text not null,
  numeric_value numeric,
  unit text,
  importance int not null default 3 check (importance between 1 and 5),
  position int not null default 0,
  source_url text,
  source_note text,
  is_published boolean not null default true
);

create table public.signs (
  id uuid primary key default gen_random_uuid(),
  lesson_id uuid references public.lessons(id) on delete set null,
  code text unique,
  name text not null,
  category text not null,
  subtype text,
  meaning text not null,
  required_action text not null,
  image_path text,
  common_confusion text,
  difficulty public.difficulty_level not null default 'easy',
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.questions (
  id uuid primary key default gen_random_uuid(),
  module_id uuid not null references public.modules(id) on delete cascade,
  lesson_id uuid references public.lessons(id) on delete set null,
  sign_id uuid references public.signs(id) on delete set null,
  type public.question_kind not null default 'multiple_choice',
  prompt text not null,
  explanation text not null,
  difficulty public.difficulty_level not null default 'easy',
  position int not null default 0,
  source_url text,
  metadata jsonb not null default '{}'::jsonb,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.question_options (
  id uuid primary key default gen_random_uuid(),
  question_id uuid not null references public.questions(id) on delete cascade,
  option_text text not null,
  is_correct boolean not null default false,
  position int not null default 0
);
create unique index one_option_position_per_question on public.question_options(question_id, position);
create index questions_module_idx on public.questions(module_id);
create index facts_lesson_idx on public.facts(lesson_id);

create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.lesson_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id uuid not null references public.lessons(id) on delete cascade,
  status public.progress_state not null default 'not_started',
  mastery numeric(5,2) not null default 0 check (mastery between 0 and 100),
  best_score numeric(5,2) not null default 0 check (best_score between 0 and 100),
  last_studied_at timestamptz,
  completed_at timestamptz,
  primary key(user_id, lesson_id)
);

create table public.question_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id uuid not null references public.questions(id) on delete cascade,
  selected_option_id uuid references public.question_options(id) on delete set null,
  is_correct boolean not null,
  response_ms int,
  mode text not null default 'practice' check (mode in ('lesson','practice','mock')),
  created_at timestamptz not null default now()
);
create index attempts_user_question_idx on public.question_attempts(user_id, question_id, created_at desc);

create table public.mock_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  rules_score int not null default 0,
  signs_score int not null default 0,
  controls_score int not null default 0,
  passed boolean not null default false,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create table public.mock_answers (
  id bigint generated by default as identity primary key,
  mock_attempt_id uuid not null references public.mock_attempts(id) on delete cascade,
  question_id uuid not null references public.questions(id) on delete cascade,
  selected_option_id uuid references public.question_options(id) on delete set null,
  is_correct boolean not null
);

-- Sign artwork bucket. Upload official/licensed SVG/PNG assets later.
insert into storage.buckets (id, name, public) values ('road-signs','road-signs',true) on conflict (id) do nothing;

-- RLS
alter table public.modules enable row level security;
alter table public.lessons enable row level security;
alter table public.facts enable row level security;
alter table public.signs enable row level security;
alter table public.questions enable row level security;
alter table public.question_options enable row level security;
alter table public.profiles enable row level security;
alter table public.lesson_progress enable row level security;
alter table public.question_attempts enable row level security;
alter table public.mock_attempts enable row level security;
alter table public.mock_answers enable row level security;

-- Public study content can be read, never edited by normal clients.
create policy modules_public_read on public.modules for select to anon, authenticated using (is_published);
create policy lessons_public_read on public.lessons for select to anon, authenticated using (is_published);
create policy facts_public_read on public.facts for select to anon, authenticated using (is_published);
create policy signs_public_read on public.signs for select to anon, authenticated using (is_published);
-- Questions/options are intentionally NOT granted to anon/authenticated. They are delivered via Nuxt server routes so correct answers stay server-side.

create policy profile_own_select on public.profiles for select to authenticated using (auth.uid() = user_id);
create policy profile_own_insert on public.profiles for insert to authenticated with check (auth.uid() = user_id);
create policy profile_own_update on public.profiles for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy lesson_progress_own_all on public.lesson_progress for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy question_attempts_own_select on public.question_attempts for select to authenticated using (auth.uid() = user_id);
create policy question_attempts_own_insert on public.question_attempts for insert to authenticated with check (auth.uid() = user_id);
create policy mock_attempts_own_all on public.mock_attempts for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy mock_answers_own_select on public.mock_answers for select to authenticated using (exists(select 1 from public.mock_attempts m where m.id=mock_attempt_id and m.user_id=auth.uid()));
create policy mock_answers_own_insert on public.mock_answers for insert to authenticated with check (exists(select 1 from public.mock_attempts m where m.id=mock_attempt_id and m.user_id=auth.uid()));

-- Least privilege grants
grant usage on schema public to anon, authenticated;
grant select on public.modules, public.lessons, public.facts, public.signs to anon, authenticated;
grant select, insert, update on public.profiles, public.lesson_progress, public.mock_attempts to authenticated;
grant select, insert on public.question_attempts, public.mock_answers to authenticated;
grant usage, select on all sequences in schema public to authenticated;
